#!/usr/bin/env python3
"""Build the HawarysAddon_QuestData load-on-demand addon from QuestieDB's Forever data.

QuestieDB (https://github.com/Questie/QuestieDB) – quest, NPC, object and item data for
WoW Forever. The Questie team allows copying under GPLv3 (see their LICENSE.md); Hawary's
Addon is GPLv3 and credits them. We do NOT use the Questie name or logo for branding.

The tables are copied unchanged (as Lua source strings, decoded lazily in game exactly like
Questie does), so the runtime reader sees the same shapes as QuestieDB's public API.

Usage:
  python3 tools/build_questdata.py <questiedb checkout or download dir>
Expected input files (relative to that dir):
  data/Forever/forever{Quest,Npc,Object,Item}DB.lua
  support/Forever/Zones/areaIdToUiMapId.lua
"""
import datetime
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "HawarysAddon_QuestData")

SOURCES = {
    "quest": ("data/Forever/foreverQuestDB.lua", "QuestieDB.questData"),
    "npc": ("data/Forever/foreverNpcDB.lua", "QuestieDB.npcData"),
    "object": ("data/Forever/foreverObjectDB.lua", "QuestieDB.objectData"),
    "item": ("data/Forever/foreverItemDB.lua", "QuestieDB.itemData"),
    "areaToUiMapOverride": ("support/Forever/Zones/areaIdToUiMapId.lua", "ZoneDB.private.areaIdToUiMapIdOverride"),
    "areaToUiMap": ("support/Forever/Zones/areaIdToUiMapId.lua", "ZoneDB.private.areaIdToUiMapId"),
}


def extract(path, assign):
    text = open(path, encoding="utf-8").read()
    m = re.search(re.escape(assign) + r"\s*=\s*\[\[(return \{.*?\n\})\]\]", text, re.S)
    if not m:
        raise SystemExit(f"could not find {assign} in {path}")
    payload = m.group(1)
    if "]==]" in payload:
        raise SystemExit(f"{assign}: payload contains ]==]")
    return payload


def count_entries(payload):
    # Standard Lua (not LuaJIT, which caps a chunk at 65,536 constants; WoW's Lua does not).
    lua = "local t = assert(load(io.read('a')))(); local n = 0; for _ in pairs(t) do n = n + 1 end; print(n)"
    r = subprocess.run(["lua", "-e", lua], input=payload, capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"payload does not load: {r.stderr.strip()}")
    return int(r.stdout.strip())


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    src = sys.argv[1]
    os.makedirs(OUT, exist_ok=True)
    counts = {}
    for key, (rel, assign) in SOURCES.items():
        payload = extract(os.path.join(src, rel), assign)
        counts[key] = count_entries(payload)
        with open(os.path.join(OUT, "Data_" + key + ".lua"), "w", encoding="utf-8") as fh:
            fh.write("-- Generated by tools/build_questdata.py from QuestieDB (GPLv3). Do not edit.\n")
            fh.write("HawarysQuestData = HawarysQuestData or {}\n")
            fh.write(f"HawarysQuestData.{key} = [==[{payload}]==]\n")
    built = datetime.date.today().isoformat()
    with open(os.path.join(OUT, "Data_info.lua"), "w", encoding="utf-8") as fh:
        fh.write("-- Generated by tools/build_questdata.py. Do not edit.\n")
        fh.write("HawarysQuestData = HawarysQuestData or {}\n")
        fh.write('HawarysQuestData.info = { source = "QuestieDB (Forever)", built = "%s", quests = %d, npcs = %d, objects = %d, items = %d }\n'
                 % (built, counts["quest"], counts["npc"], counts["object"], counts["item"]))
    with open(os.path.join(OUT, "HawarysAddon_QuestData.toc"), "w", encoding="utf-8") as fh:
        fh.write("## Interface: 16001\n")
        fh.write("## Title: |cff38c6f4Hawary's|r Addon – Quest Data\n")
        fh.write("## Notes: Quest, NPC, object and item data for Hawary's Addon (from QuestieDB, GPLv3). Loaded only when needed.\n")
        fh.write("## Author: Hawary\n")
        fh.write("## Version: 1.0.0\n")
        fh.write("## LoadOnDemand: 1\n")
        fh.write("## Dependencies: HawarysAddon\n")
        fh.write("## IconTexture: Interface\\AddOns\\HawarysAddon\\Media\\logo\n")
        fh.write("## X-License: GPL-3.0-or-later\n\n")
        for key in ["info"] + list(SOURCES):
            fh.write(f"Data_{key}.lua\n")
    with open(os.path.join(OUT, "CREDITS.md"), "w", encoding="utf-8") as fh:
        fh.write("# Quest data credits\n\n")
        fh.write("The quest, NPC, object, item and zone tables in this folder come from **QuestieDB**\n")
        fh.write("(https://github.com/Questie/QuestieDB), WoW Forever data, copied unchanged.\n\n")
        fh.write("The Questie team allows forking and copying under the terms of the GNU GPLv3\n")
        fh.write("(see QuestieDB's and Questie's LICENSE.md, including their note about historic contributors).\n")
        fh.write("Hawary's Addon is licensed GPL-3.0-or-later. It is not affiliated with or endorsed by the\n")
        fh.write("Questie team, and does not use the Questie name or logo for its branding.\n\n")
        fh.write("Thank you to everyone who built and maintains that data.\n")
    with open(os.path.join(ROOT, "LICENSE"), encoding="utf-8") as a, open(os.path.join(OUT, "LICENSE"), "w", encoding="utf-8") as b:
        b.write(a.read())
    print("quest data built:", counts)


if __name__ == "__main__":
    main()
